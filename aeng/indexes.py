from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any

import yaml

from .config import load_config
from .documents import parse_document, parse_table, read_h1, replace_marked_section

PLAN_START = "<!-- AENG:PLANS:START -->"
PLAN_END = "<!-- AENG:PLANS:END -->"
DECISION_START = "<!-- AENG:DECISIONS:START -->"
DECISION_END = "<!-- AENG:DECISIONS:END -->"
MANUAL_START = "<!-- AENG:MANUAL:START -->"
MANUAL_END = "<!-- AENG:MANUAL:END -->"
PROJECT_START = "<!-- AENG:PROJECT:START -->"
PROJECT_END = "<!-- AENG:PROJECT:END -->"


def _documents(directory: Path) -> list[tuple[Path, dict[str, Any], str]]:
    result = []
    for path in sorted(directory.glob("*.md")):
        if path.name.startswith("_") or path.name == "README.md":
            continue
        data, body = parse_document(path)
        result.append((path, data, body))
    return result


def _cell(value: Any) -> str:
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ")


def generate_plan_index(root: Path) -> str:
    plans = []
    for path, data, _ in _documents(root / "engineering/plans"):
        _, rows = parse_table(path.read_text(encoding="utf-8"), "Slices")
        landed = sum(row.get("status") == "landed" for row in rows)
        plans.append({
            "id": data.get("id", path.stem),
            "file": path.name,
            "module": data.get("module", ""),
            "type": data.get("type", ""),
            "status": data.get("status", ""),
            "updated": str(data.get("updated", "")),
            "progress": f"{landed}/{len(rows)}" if rows else "0/0",
        })
    return yaml.safe_dump({"plans": plans}, sort_keys=False, allow_unicode=True)


def generate_decision_index(root: Path) -> str:
    lines = ["| ID | Title | Module | Decision | Date |", "|---|---|---|---|---|"]
    for path, data, _ in _documents(root / "engineering/decisions"):
        lines.append(
            f"| [{_cell(data.get('id'))}]({path.name}) | {_cell(read_h1(path))} | "
            f"{_cell(data.get('module'))} | {_cell(data.get('decision'))} | {_cell(data.get('date'))} |"
        )
    return "\n".join(lines)


def generate_manual_index(root: Path) -> str:
    lines = ["| Entry | Module | Status | Created | Updated | Issue |", "|---|---|---|---|---|---|"]
    for path, data, _ in _documents(root / "engineering/manual-tests"):
        if data.get("status") not in {"pending", "failed", "blocked"}:
            continue
        lines.append(
            f"| [{_cell(path.stem)}]({path.name}) | {_cell(data.get('module'))} | "
            f"{_cell(data.get('status'))} | {_cell(data.get('created'))} | {_cell(data.get('updated'))} | "
            f"{_cell(data.get('issue'))} |"
        )
    return "\n".join(lines)


def generate_project(root: Path, config: dict[str, Any]) -> str:
    plan_docs = _documents(root / "engineering/plans")
    decision_docs = _documents(root / "engineering/decisions")
    manual_docs = _documents(root / "engineering/manual-tests")
    module_docs = _documents(root / "engineering/modules")
    plan_counts = Counter(str(data.get("status", "unknown")) for _, data, _ in plan_docs)
    manual_counts = Counter(str(data.get("status", "unknown")) for _, data, _ in manual_docs)
    lines = [
        f"> **{config['project']['name']}** — languages: {', '.join(config['project']['languages'])}. "
        "Generated by `aeng index`; edit the source artifacts instead.",
        "",
        "## Module index",
        "",
        "| Module | Card | Responsibility |",
        "|---|---|---|",
    ]
    for path, data, _ in module_docs:
        lines.append(f"| {_cell(data.get('name', path.stem))} | [{path.name}](modules/{path.name}) | {_cell(data.get('responsibility'))} |")
    lines.extend(["", "## Feature maturity", "", "| Feature | Module | Maturity | Docs | Tests | Notes |", "|---|---|---|---|---|---|"])
    for path, data, body in module_docs:
        _, rows = parse_table(body, "Features")
        for row in rows:
            lines.append(
                f"| {_cell(row.get('feature'))} | {_cell(data.get('name', path.stem))} | "
                f"{_cell(row.get('maturity'))} | {_cell(row.get('docs'))} | {_cell(row.get('tests'))} | "
                f"{_cell(row.get('notes'))} |"
            )
    lines.extend(["", "## Plan summary", "", "| Status | Count |", "|---|---|"])
    for status in ["draft", "in-progress", "dev-finished", "blocked", "done", "superseded", "abandoned"]:
        lines.append(f"| {status} | {plan_counts.get(status, 0)} |")
    lines.extend(["", "## Active plans", "", "| Plan | Module | Status | Progress | Updated |", "|---|---|---|---|---|"])
    index = yaml.safe_load(generate_plan_index(root))["plans"]
    for item in index:
        if item["status"] in {"done", "superseded", "abandoned"}:
            continue
        lines.append(
            f"| [{item['id']}](plans/{item['file']}) | {_cell(item['module'])} | {_cell(item['status'])} | "
            f"{_cell(item['progress'])} | {_cell(item['updated'])} |"
        )
    lines.extend([
        "",
        "## Verification summary",
        "",
        f"- Manual checks: {len(manual_docs)} total; {manual_counts.get('pending', 0)} pending; "
        f"{manual_counts.get('failed', 0)} failed; {manual_counts.get('blocked', 0)} blocked.",
        f"- Durable decisions: {len(decision_docs)}.",
        "- Test commands and broad-change fallbacks: `.agent-engineering.yaml`.",
        "",
    ])
    return "\n".join(lines)


def generated_documents(root: Path, config: dict[str, Any]) -> dict[str, str]:
    decisions_path = root / "engineering/decisions/README.md"
    manual_path = root / "engineering/manual-tests/README.md"
    project_path = root / "engineering/PROJECT.md"
    return {
        "engineering/plans/INDEX.yaml": generate_plan_index(root),
        "engineering/decisions/README.md": replace_marked_section(
            decisions_path.read_text(encoding="utf-8"), DECISION_START, DECISION_END, generate_decision_index(root)
        ),
        "engineering/manual-tests/README.md": replace_marked_section(
            manual_path.read_text(encoding="utf-8"), MANUAL_START, MANUAL_END, generate_manual_index(root)
        ),
        "engineering/PROJECT.md": replace_marked_section(
            project_path.read_text(encoding="utf-8"), PROJECT_START, PROJECT_END, generate_project(root, config)
        ),
    }


def update_indexes(root: Path) -> None:
    config = load_config(root)
    for relative, content in generated_documents(root, config).items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content.rstrip() + "\n", encoding="utf-8", newline="\n")
